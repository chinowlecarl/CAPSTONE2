ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS archived_at timestamptz,
  ADD COLUMN IF NOT EXISTS archived_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS public.activity_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  actor_id uuid,
  actor_name text NOT NULL DEFAULT 'unknown',
  actor_role text,
  action text NOT NULL,
  entity_type text,
  entity_id text,
  summary text NOT NULL,
  details jsonb,
  ip text,
  user_agent text
);

CREATE INDEX IF NOT EXISTS activity_logs_created_at_idx
  ON public.activity_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS activity_logs_actor_id_idx
  ON public.activity_logs (actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS activity_logs_action_idx
  ON public.activity_logs (action, created_at DESC);

ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.log_profile_created()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.activity_logs (
    actor_id, actor_name, actor_role, action, entity_type, entity_id, summary
  ) VALUES (
    NEW.id,
    COALESCE(NULLIF(NEW.username, ''), 'New customer'),
    COALESCE(NEW.role, 'customer'),
    'ACCOUNT_CREATED',
    'user',
    NEW.id::text,
    'Created an account'
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS profiles_activity_created ON public.profiles;
CREATE TRIGGER profiles_activity_created
  AFTER INSERT ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.log_profile_created();

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.profiles
    GROUP BY lower(btrim(username))
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Cannot add unique usernames: profiles contains duplicate usernames when compared case-insensitively. Resolve duplicates, then rerun this migration.';
  END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS profiles_username_lower_idx
  ON public.profiles (lower(btrim(username)));

CREATE OR REPLACE FUNCTION public.username_exists(p_username text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE lower(btrim(username)) = lower(btrim(p_username))
  );
$$;

REVOKE ALL ON FUNCTION public.username_exists(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.username_exists(text) TO service_role;

CREATE OR REPLACE FUNCTION public.purge_archived_products(p_days integer DEFAULT 10)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  removed record;
  removed_count integer := 0;
  kept_count integer := 0;
BEGIN
  IF p_days < 1 THEN
    RAISE EXCEPTION 'Archive retention must be at least one day';
  END IF;

  FOR removed IN
    SELECT product.id, product.title
    FROM public.products AS product
    WHERE product.archived_at IS NOT NULL
      AND product.archived_at <= now() - make_interval(days => p_days)
    ORDER BY product.archived_at
  LOOP
    IF EXISTS (
      SELECT 1
      FROM public.order_items AS item
      WHERE item.product_id = removed.id
    ) THEN
      kept_count := kept_count + 1;
      CONTINUE;
    END IF;

    DELETE FROM public.cart_items WHERE product_id = removed.id;
    DELETE FROM public.products WHERE id = removed.id;

    INSERT INTO public.activity_logs (
      actor_name, actor_role, action, entity_type, entity_id, summary, details
    ) VALUES (
      'Archive cleanup job',
      'system',
      'PRODUCT_PURGED',
      'product',
      removed.id::text,
      format('Permanently deleted archived product "%s" after %s days', removed.title, p_days),
      jsonb_build_object('retentionDays', p_days)
    );
    removed_count := removed_count + 1;
  END LOOP;

  RETURN jsonb_build_object(
    'deleted', removed_count,
    'kept_in_order_history', kept_count
  );
END;
$$;

REVOKE ALL ON FUNCTION public.purge_archived_products(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.purge_archived_products(integer) TO service_role;

CREATE EXTENSION IF NOT EXISTS pg_cron;

DO $$
DECLARE
  existing_job bigint;
BEGIN
  SELECT jobid INTO existing_job
  FROM cron.job
  WHERE jobname = 'purge-archived-products';

  IF existing_job IS NOT NULL THEN
    PERFORM cron.unschedule(existing_job);
  END IF;

  PERFORM cron.schedule(
    'purge-archived-products',
    '0 3 * * *',
    'SELECT public.purge_archived_products(10)'
  );
END
$$;
